# 연습 데이터/기록 안내는 급수·순위만 다르므로 규칙으로 만든다
_G = {"特級": "특급", "上級": "상급", "中級": "중급", "初級": "초급"}
_R = {"壱位": "１위", "弐位": "２위", "参位": "３위"}
