# 반각은 글리프가 없어 화면에 안 나온다. 문장부호와 공백만 전각으로 바꾸고
# **알파벳과 밑줄은 그대로 둔다** — 문장 끝의 제어 코드(B c H I _)이기 때문이다.
PUNCT = {'.': '．', ',': '，', '!': '！', '?': '？', '(': '（', ')': '）',
         '~': '～', "'": '’', '"': '”', ':': '：', ';': '；', ' ': '　',
         '·': '・'}

def norm(s):
    out, i = [], 0
    while i < len(s):
        if s.startswith('\\n', i):          # 줄바꿈 이스케이프는 건드리지 않는다
            out.append('\\n'); i += 2; continue
        c = s[i]; i += 1
        out.append(PUNCT.get(c, c))
    return ''.join(out)

