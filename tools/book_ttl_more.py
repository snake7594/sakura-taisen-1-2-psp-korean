def clear(img, x0, x1, bands):
    for b in bands:
        img[b*32:(b+1)*32, x0:x1] = 0

def apply_ep96(img):
    clear(img, *EP_H96_CLEAR, bands=(0, 1, 2))
    for (nx0, nx1), (sx0, sx1), num, l1, l2 in EP_H96:
        draw(img, nx0, nx1, num, 32, 64, ink=15, gh=26, cy=15)   # 밴드1 = 第N話
        draw(img, sx0, sx1, l1,  64, 96, ink=15, gh=26, cy=15)   # 밴드2 = 윗줄
        draw(img, sx0, sx1, l2,   0, 32, ink=15, gh=26, cy=15)   # 밴드0 = 아랫줄
        print(f"  x{sx0}~{sx1}  {num}  {l1} / {l2}")

def apply_ep64(img):
    for a, b in EP_H64_CLEAR:
        clear(img, a, b, bands=(0, 1))
    for (nx0, nx1), (sx0, sx1), num, sub in EP_H64:
        draw(img, nx0, nx1, num, 0, 32, ink=15, gh=26, cy=15)    # 밴드0 = 第N話
        draw(img, sx0, sx1, sub, 32, 64, ink=15, gh=26, cy=15)   # 밴드1 = 부제
        print(f"  x{sx0}~{sx1}  {num}  {sub}")

def run(check_only=False, make_png=False):
    raw = open(SRC, 'rb').read()
    s2  = bytes(decompress(raw[SPLIT:])[0])
    n2  = len(s2)
    img = BF.unpack(s2, 96)
    print(f"  H96 레이어 {img.shape[1]:,} x {img.shape[0]}")
    before = img.copy()
    apply(img, WORDS)

    if make_png:
        os.makedirs(os.path.join(ROOT, "test_render", "ttl96"), exist_ok=True)
        for k, (x0, x1, ja, ko) in enumerate(WORDS):
            a, b = max(0, x0-20), min(img.shape[1], x1+20)
            sh = Image.new('L', ((b-a), 96*2+6), 60)
            sh.paste(Image.fromarray((before[:, a:b]*17).astype(np.uint8)), (0, 0))
            sh.paste(Image.fromarray((img[:, a:b]*17).astype(np.uint8)), (0, 96+6))
            sh.resize(((b-a)*5, sh.height*5), Image.NEAREST).save(
                os.path.join(ROOT, "test_render", "ttl96", f"w{k:02d}_{x0}.png"))
        print(f"      미리보기 {len(WORDS)}장 -> test_render/ttl96/w*.png")
        return

    apply_cmd(img)
    apply_ep96(img)
    s2 = BF.store(img, n2)
    img64 = BF.unpack(s2, 64)
    print(f"  H64 레이어 {img64.shape[1]:,} x {img64.shape[0]}")
    apply_ep64(img64)
    s2 = BF.store(img64, n2)
    m, p, _, hl = parse_header(raw[SPLIT:])
    ob, bi = _params(m, p)
    packed = compress(s2, ob, bi, header=raw[SPLIT:SPLIT+hl])
    assert bytes(decompress(packed)[0]) == s2, "재압축 왕복 실패"
    merged = raw[:SPLIT] + packed
    assert bytes(decompress(merged)[0]) == bytes(decompress(raw)[0]), "스트림1 이 바뀌었다"
    print(f"  합본 {len(merged):,}B / 예산 {BUDGET:,}B  "
          f"여유 {BUDGET-len(merged):,}B  들어감={len(merged)<=BUDGET}")
    if len(merged) > BUDGET: raise RuntimeError("슬롯 초과")
    if not check_only:
        open(SRC, 'wb').write(merged)
        print(f"      -> {SRC}")

if __name__ == '__main__':
    sys.stdout = __import__('io').TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
    run('--check' in sys.argv, '--png' in sys.argv)
