def main():
    dry = '--dry' in sys.argv
    hit = 0
    for fn in FILES:
        p = os.path.join(TEXT, fn)
        if not os.path.exists(p): continue
        with open(p, encoding='utf-8-sig', newline='') as f:
            rd = csv.reader(f, delimiter='\t', quoting=csv.QUOTE_NONE)
            hdr = next(rd); rows = list(rd)
        ja_i, ko_i = hdr.index('ja'), hdr.index('ko')
        n = 0
        for r in rows:
            v = KO.get(r[ja_i])
            if v and r[ko_i] != v: r[ko_i] = v; n += 1
        hit += n
        print(f"  {fn:<18} {n:>4}행 채움 / 전체 {len(rows)}")
        if n and not dry:
            with open(p, 'w', encoding='utf-8-sig', newline='') as f:
                w = csv.writer(f, delimiter='\t', lineterminator='\n',
                               quoting=csv.QUOTE_NONE, escapechar=None)
                w.writerow(hdr); w.writerows(rows)
    print(f"\n합계 {hit}행" + (" (--dry)" if dry else ""))

if __name__ == '__main__':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
    main()
